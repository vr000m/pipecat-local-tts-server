/// A fixed spoken clip for the speech-to-text "Test Transcription" check, so a wrong
/// transcript points at the model and not at whichever system voice happens to be installed.
///
/// 16 kHz mono PCM16 (the wire format `STTClient.transcribe` takes, no header), made once with
/// `say -v Samantha --data-format=LEI16@16000`; no recording of a person.
public enum STTSampleClip {
    /// What the clip says.
    public static let sentence = "The quick brown fox jumps over the lazy dog."

    /// The clip with half a second of silence on each side: the speech starts at the first
    /// sample, and Kyutai STT 2.6B drops a first word it gets no lead-in for ("the quick
    /// brown fox" came back as "quick brown fox"; measured against the running server).
    public static let pcm16: Data = {
        let padding = Data(count: STTWire.bytesPerSecond / 2)  // 0.5 s of 16-bit samples
        let speech = Data(base64Encoded: encoded, options: .ignoreUnknownCharacters) ?? Data()
        return padding + speech + padding
    }()

    /// Whether `transcript` is the clip's sentence, ignoring case, punctuation and spacing,
    /// with 5% edit distance (about one stray character). Common words only, on purpose: a
    /// wrong word fails the check, where a brand name would be a coin toss for a small model.
    public static func matches(_ transcript: String) -> Bool {
        let want = compact(sentence)
        let got = compact(transcript)
        guard !got.isEmpty else { return false }
        return editDistance(Array(want), Array(got)) * 100 <= want.count * 5
    }

    static func compact(_ text: String) -> String {
        String(text.lowercased().unicodeScalars.filter { CharacterSet.alphanumerics.contains($0) }.map(Character.init))
    }

    static func editDistance(_ a: [Character], _ b: [Character]) -> Int {
        var row = Array(0...b.count)
        for i in stride(from: 1, through: a.count, by: 1) {
            var diagonal = row[0]
            row[0] = i
            for j in stride(from: 1, through: b.count, by: 1) {
                let above = row[j]
                row[j] = min(row[j] + 1, row[j - 1] + 1, diagonal + (a[i - 1] == b[j - 1] ? 0 : 1))
                diagonal = above
            }
        }
        return row[b.count]
    }

